// Reproducible CC0 source conversion; no existing MP3 is re-encoded.
import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const root = path.resolve('public/drums/studio-v2');
const cache = path.resolve('.sample-cache');
await fs.mkdir(cache,{recursive:true});
const config = {
 kick: ['kick','snoff',[1,2,3,4],2,'kickmic',35],
 snare: ['snare','center',[3,7,11,15,19,23,29,35],2,'snaremic',85],
 rim: ['snare','crossstick',[2,6,10,14],2,'snaremic',100],
 hh_closed: ['hh','closed',[1,2,3,4],2,'oh',350],
 hh_open: ['hh','open',[1,2,3,4],2,'oh',300],
 crash: ['crash','crash',[1,2,3],2,'oh',200],
 ride: ['ride','ride',[1,2,3],2,'oh',200],
 tom_hi: ['htom','center',[2,6,10,14],2,'mid',65],
 tom_lo: ['ltom','center',[2,6,10,14],2,'mid',45],
};
const revision = execFileSync('gh',['api','repos/sfzinstruments/virtuosity_drums/commits/master','--jq','.sha'],{encoding:'utf8'}).trim();
const tasks=[]; const levels={}; const provenance=[];
for(const [dir,[instrument,art,layers,takes,mic,hp]] of Object.entries(config)) {
 await fs.mkdir(path.join(root,dir),{recursive:true}); levels[dir]=[];
 for(let l=0;l<layers.length;l++) for(let take=0;take<takes;take++) tasks.push({dir,instrument,art,vl:layers[l],take,mic,hp,file:l*takes+take});
}
async function render(t) {
 const rr=['kick','hh','crash','ride'].includes(t.instrument);
 // Adjacent recorded velocity hits are alternatives, NOT fabricated same-velocity round robins.
 const vl=t.vl+(rr?0:t.take);
 const name=`${t.mic}_${t.instrument}_${t.art}_vl${vl}${rr?`_rr${t.take+1}`:''}.flac`;
 const source=`Samples/${t.mic}/${t.instrument}/${name}`;
 const raw=path.join(cache,name);
 try {await fs.access(raw);} catch {
  const r=await fetch(`https://raw.githubusercontent.com/sfzinstruments/virtuosity_drums/${revision}/${source}`);
  if(!r.ok) throw Error(`${r.status}: ${source}`);
  await fs.writeFile(raw,Buffer.from(await r.arrayBuffer()));
 }
 const out=path.join(root,t.dir,`${t.file}.mp3`);
 // A dedicated mic per family avoids mixing unrelated close mics equally.
 execFileSync('ffmpeg',['-v','error','-y','-i',raw,'-af',`highpass=f=${t.hp}`,'-ar','44100','-ac','2','-c:a','libmp3lame','-b:a','192k',out]);
 const pcm=execFileSync('ffmpeg',['-v','error','-i',out,'-f','f32le','-ac','2','-ar','44100','pipe:1'],{maxBuffer:32*1024*1024});
 let sum=0,peak=0; const n=Math.min(8820,pcm.length/4);
 for(let i=0;i<pcm.length/4;i++){const x=pcm.readFloatLE(i*4);peak=Math.max(peak,Math.abs(x));if(i<n)sum+=x*x;}
 if(peak>=1) throw Error(`clipping: ${source}`);
 levels[t.dir][t.file]=20*Math.log10(Math.sqrt(sum/n));
 provenance.push({output:`${t.dir}/${t.file}.mp3`,source,peakDb:20*Math.log10(peak),attackDb:levels[t.dir][t.file]});
 console.log(`built ${t.dir}/${t.file}`);
}
let cursor=0;
await Promise.all(Array.from({length:4},async()=>{while(cursor<tasks.length)await render(tasks[cursor++]);}));
await fs.writeFile(path.join(root,'provenance.json'),JSON.stringify({revision,license:'CC0-1.0',files:provenance},null,2));
await fs.writeFile('src/audio/studioV2Levels.ts',`// Generated by scripts/build-studio-v2.mjs from decoded output.\nexport const STUDIO_V2_LEVELS: Record<string, readonly number[]> = ${JSON.stringify(levels,null,2)};\n`);
console.log(`Finished ${tasks.length} source recordings`);
